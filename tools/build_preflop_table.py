"""Build src/preflop_table.py: equity and percentile for every 3-card hand.

Equity = P(win) + P(tie)/2 against a random 3-card opponent, with BOTH players
discarding by the cheap rule on the flop. One representative per suit-isomorphic
class (1,755 classes) is simulated; results are expanded to all 22,100 hands.

Usage: py -3.11 tools\build_preflop_table.py [samples_per_class] [processes]
"""
import base64, itertools, os, sys, time
from multiprocessing import Pool
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "src"))
import numpy as np
from cards import RANKS, card_str
from evaluator import eval_batch, cheap_keep_batch

PERMS = list(itertools.permutations(range(4)))


def canon(cards):
    best = None
    for p in PERMS:
        t = tuple(sorted(((12 - (c >> 2)), p[c & 3]) for c in cards))
        if best is None or t < best:
            best = t
    return best


def key_str(t):
    return "".join(RANKS[12 - r] + "abcd"[s] for r, s in t)


def simulate(args):
    hand, n, seed = args
    rng = np.random.default_rng(seed)
    rest = np.array([c for c in range(52) if c not in hand], dtype=np.int64)
    pick = rest[np.argsort(rng.random((n, 49)), axis=1)[:, :8]]
    opp, board = pick[:, :3], pick[:, 3:]
    me = np.tile(np.array(hand, dtype=np.int64), (n, 1))
    flop = board[:, :3]
    mk, _ = cheap_keep_batch(me, flop)
    ok, _ = cheap_keep_batch(opp, flop)
    a = eval_batch(np.concatenate([mk, board], axis=1))
    b = eval_batch(np.concatenate([ok, board], axis=1))
    return float(((a > b).sum() + 0.5 * (a == b).sum()) / n)


def main():
    n = int(sys.argv[1]) if len(sys.argv) > 1 else 20000
    procs = int(sys.argv[2]) if len(sys.argv) > 2 else max(1, (os.cpu_count() or 2) - 1)
    hands = sorted(itertools.combinations(range(52), 3),          # each a < b < c,
                   key=lambda h: (h[2], h[1], h[0]))               # in hand_index order
    classes = {}
    for h in hands:
        classes.setdefault(canon(h), []).append(h)
    keys = sorted(classes)
    print(f"{len(hands)} hands, {len(keys)} classes, {n} samples per class, {procs} processes")
    t0 = time.time()
    jobs = [(classes[k][0], n, 1000 + i) for i, k in enumerate(keys)]
    with Pool(procs) as pool:
        eqs = pool.map(simulate, jobs, chunksize=8)
    print(f"simulated in {time.time() - t0:.0f} s")
    eq_class = dict(zip(keys, eqs))
    eq = np.array([eq_class[canon(h)] for h in hands])           # in hand_index order
    order = np.argsort(-eq, kind="stable")
    q = np.empty(len(hands))
    # percentile from the top: share of hands strictly better (ties share a value)
    sorted_eq = eq[order]
    better = np.searchsorted(-sorted_eq, -eq, side="left")
    q = better / len(hands)

    # report
    n_ranks = {}
    for k in keys:
        kinds = len({r for r, _ in k})
        n_ranks[kinds] = n_ranks.get(kinds, 0) + 1
    pair_share = sum(len(classes[k]) for k in keys if len({r for r, _ in k}) < 3) / len(hands)
    print("classes by distinct ranks:", n_ranks, "| share of hands with a pair or better: %.4f" % pair_share)
    ranked = sorted(keys, key=lambda k: -eq_class[k])
    print("top 20:", ", ".join(f"{key_str(k)} {eq_class[k]:.3f}" for k in ranked[:20]))
    print("bottom 10:", ", ".join(f"{key_str(k)} {eq_class[k]:.3f}" for k in ranked[-10:]))
    for p in (0.01, 0.05, 0.10, 0.25, 0.50, 0.75, 0.90):
        print(f"equity at top {int(p * 100)}%: {sorted_eq[int(p * len(hands))]:.3f}")
    print(f"min {eq.min():.3f} max {eq.max():.3f} mean {eq.mean():.4f}")

    eq16 = np.round(eq * 10000).astype("<u2")
    q16 = np.round(q * 65535).astype("<u2")
    out = os.path.join(ROOT, "src", "preflop_table.py")
    with open(out, "w", encoding="ascii", newline="\n") as f:
        f.write('"""Generated by tools/build_preflop_table.py - do not edit.\n')
        f.write("PF_EQ[i] = equity * 10000, PF_Q[i] = percentile from the top * 65535 (0 = best),\n")
        f.write("i = hand_index(a, b, c) for card ids a < b < c. %d samples per class.\n" % n)
        f.write('"""\nimport base64\nfrom array import array\n\n')
        f.write("_C2 = [b * (b - 1) // 2 for b in range(52)]\n")
        f.write("_C3 = [c * (c - 1) * (c - 2) // 6 for c in range(52)]\n\n\n")
        f.write("def hand_index(a, b, c):\n    \"\"\"Index of a 3-card hand; any order.\"\"\"\n")
        f.write("    if a > b:\n        a, b = b, a\n    if b > c:\n        b, c = c, b\n    if a > b:\n        a, b = b, a\n")
        f.write("    return _C3[c] + _C2[b] + a\n\n\n")
        for name, arr in (("PF_EQ", eq16), ("PF_Q", q16)):
            b64 = base64.b64encode(arr.tobytes()).decode("ascii")
            f.write(f"_{name}_B64 = (\n")
            for i in range(0, len(b64), 100):
                f.write(f'    "{b64[i:i + 100]}"\n')
            f.write(")\n")
            f.write(f"{name} = array('H')\n{name}.frombytes(base64.b64decode(_{name}_B64))\n")
            f.write("import sys as _sys\nif _sys.byteorder != 'little':\n    %s.byteswap()\n\n" % name)
        f.write("\ndef preflop_equity(a, b, c):\n    return PF_EQ[hand_index(a, b, c)] / 10000.0\n\n\n")
        f.write("def preflop_q(a, b, c):\n    return PF_Q[hand_index(a, b, c)] / 65535.0\n")
    print("wrote", out, os.path.getsize(out), "bytes")
    # check the index is the combination order used above
    sys.path.insert(0, os.path.join(ROOT, "src"))
    import importlib, preflop_table
    importlib.reload(preflop_table)
    assert all(preflop_table.hand_index(*h) == i for i, h in enumerate(hands)), "index mismatch"
    print("index check OK")


if __name__ == "__main__":
    main()
